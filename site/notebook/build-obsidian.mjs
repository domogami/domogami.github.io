import { compile, compileString } from "sass"
import { format, resolveConfig } from "prettier"
import { readFile, mkdir, writeFile, copyFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const root = new URL("./", import.meta.url)
const font = await readFile(new URL("../../quartz/static/fonts/notebook-caveat.woff2", root))
const shared = compile(fileURLToPath(new URL("annotations.scss", root))).css
const css = `/* Generated by site/notebook/build-obsidian.mjs. Edit annotations.scss.
   Caveat is bundled offline under the SIL Open Font License; see caveat-OFL.txt. */
@font-face {
  font-family: "Notebook Caveat";
  src: url("data:font/woff2;base64,${font.toString("base64")}") format("woff2");
  font-weight: 400 700;
  font-style: normal;
  font-display: swap;
}
.callout[data-callout="annotation"] {
  --tertiary: var(--notebook-annotation-accent, #a34e36);
  --darkgray: var(--text-normal);
  --bodyFont: var(--font-text);
  --callout-color: 163, 78, 54;
  --callout-icon: lucide-pencil-line;
  mix-blend-mode: normal;
}
.theme-dark .callout[data-callout="annotation"] {
  --tertiary: var(--notebook-annotation-accent, #e6b78d);
  --callout-color: 230, 183, 141;
}
${shared}
`
await mkdir(new URL("obsidian/", root), { recursive: true })
await writeFile(
  new URL("obsidian/notebook-annotations.css", root),
  await format(css, { ...(await resolveConfig(fileURLToPath(root))), parser: "css" }),
)
await copyFile(
  new URL("../../quartz/static/fonts/caveat-OFL.txt", root),
  new URL("obsidian/caveat-OFL.txt", root),
)
console.log(
  "Built standalone Obsidian snippet from shared annotation styles (font included offline)",
)

// Garden already embeds Caveat. Scope this integration above theme selectors,
// sharing the website geometry without duplicating the font or theme settings.
const garden = compileString(`
body .workspace-leaf-content[data-type="markdown"] {
  .callout[data-callout="annotation"] {
    --tertiary: var(--notebook-annotation-accent, #a34e36);
    --darkgray: var(--text-normal);
    --bodyFont: var(--font-text);
    --callout-color: 163, 78, 54;
    mix-blend-mode: normal;
    box-shadow: none;
    > .callout-title { color: var(--tertiary); }
  }
  ${shared.replaceAll('"Notebook Caveat"', '"Garden Caveat"')}
}
body.theme-dark .workspace-leaf-content[data-type="markdown"] .callout[data-callout="annotation"] {
  --tertiary: var(--notebook-annotation-accent, #e6b78d);
  --callout-color: 230, 183, 141;
}
`).css
await writeFile(
  new URL("obsidian/garden-annotations.css", root),
  await format(
    `/* BEGIN GARDEN ANNOTATIONS
Generated by site/notebook/build-obsidian.mjs from annotations.scss.
Append this section to garden.css so the existing Garden toggle owns it.
Uses Garden's embedded Caveat font. No note changes or plugin required.
*/\n${garden}\n/* END GARDEN ANNOTATIONS */\n`,
    {
      ...(await resolveConfig(fileURLToPath(root))),
      parser: "css",
    },
  ),
)
console.log("Built Garden annotation integration (reuses Garden Caveat)")
